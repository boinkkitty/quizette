// Package domain holds Quizette's core model: aggregates, value objects and
// domain services. It depends only on the Go standard library.
package domain

import (
	"errors"
	"strings"
)

// Sentinel errors that adapters map to transport-level responses.
var (
	ErrNotFound          = errors.New("not found")
	ErrConflict          = errors.New("conflict")
	ErrUnauthorized      = errors.New("unauthorized")
	ErrInvalidTransition = errors.New("invalid state transition")
)

// ValidationError lists every rule a value broke. It is returned instead of
// failing on the first problem so callers (and LLM retries) see the full set.
type ValidationError struct {
	Problems []string
}

func (e *ValidationError) Error() string {
	return "validation failed: " + strings.Join(e.Problems, "; ")
}

// newValidationError returns nil when there are no problems.
func newValidationError(problems []string) error {
	if len(problems) == 0 {
		return nil
	}
	return &ValidationError{Problems: problems}
}

// Invalid builds a ValidationError with a single problem.
func Invalid(problem string) error {
	return &ValidationError{Problems: []string{problem}}
}

// ID identifies an entity. Values are UUIDv7 strings generated by the app layer.
type ID string

func (id ID) String() string { return string(id) }
